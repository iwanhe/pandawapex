create table if not exists departemen (
     deptno  int  generated by default as identity primary key
   , nama    text not null unique
   , lokasi  text not null
);

create table if not exists karyawan (
     empno      int           generated by default as identity primary key
   , nama       text          not null
   , jabatan    text
   , deptno     int           references departemen (deptno)
   , tgl_masuk  date          not null default current_date
   , gaji       numeric(14,2) not null check (gaji > 0)
   , aktif      boolean       not null default true
);
create index if not exists karyawan_deptno_ix on karyawan (deptno);


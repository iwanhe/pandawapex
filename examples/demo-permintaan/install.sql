/** Nomor dokumen berikutnya: PREFIX-YYYY-NNNN (prefix dari apx_demo_doc_types). */
create or replace function apx_demo_doc_pkg.next_no(p_doc_type text, p_date date default current_date)
returns text language plpgsql
set search_path = apx_demo, pg_temp
as $$
declare
   l_prefix apx_demo_doc_types.prefix%type;
   l_period apx_demo_doc_seq.period%type := to_char(coalesce(p_date, current_date), 'YYYY');
   l_no     apx_demo_doc_seq.last_no%type;
begin
   select prefix into strict l_prefix from apx_demo_doc_types where doc_type = p_doc_type;
   -- Oracle: merge (buat baris periode) lalu update ... returning. Di sini satu perintah atomik.
   insert into apx_demo_doc_seq as s (doc_type, period, last_no)
   values (p_doc_type, l_period, 1)
   on conflict (doc_type, period) do update set last_no = s.last_no + 1
   returning last_no into l_no;
   return l_prefix || '-' || l_period || '-' || lpad(l_no::text, 4, '0');
end;
$$;


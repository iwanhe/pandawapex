-- 5. Package APX_DEMO_APPROVAL_PKG: approval engine
-- =============================================================================
create or replace function apx_demo_approval_pkg.package_version()
returns text language sql immutable
as $$ select '01.00.00' $$;

/** TRUE saat perubahan status sedang dilakukan oleh package ini (dipakai trigger guard). Oracle: variabel package. */
create or replace function apx_demo_approval_pkg.bypass()
returns boolean language sql stable
as $$ select coalesce(current_setting('apx_demo.bypass', true), '') = 'on' $$;

/** Set bypass (untuk seed/migrasi data), hanya untuk transaksi berjalan. Selalu kembalikan ke FALSE setelah selesai. */
create or replace function apx_demo_approval_pkg.set_bypass(p_value boolean)
returns void language sql
as $$ select set_config('apx_demo.bypass', case when p_value then 'on' else 'off' end, true) $$;

create or replace function apx_demo_approval_pkg.get_type(p_doc_type text)
returns apx_demo.apx_demo_doc_types language plpgsql stable
set search_path = apx_demo, pg_temp
as $$
declare
   r_type apx_demo_doc_types%rowtype;
begin
   select * into r_type from apx_demo_doc_types where doc_type = p_doc_type;
   if not found then
      raise exception 'Jenis dokumen % tidak dikenal.', p_doc_type using errcode = 'P0001', hint = 'ORA-20100';
   end if;
   return r_type;
end;
$$;

-- nama tabel/kolom dari konfigurasi: format('%I') menggantikan dbms_assert.simple_sql_name
create or replace function apx_demo_approval_pkg.get_doc(r_type apx_demo.apx_demo_doc_types, p_doc_id bigint
                                                       , out x_doc_no text, out x_status text)
language plpgsql stable
set search_path = apx_demo, pg_temp
as $$
begin
   execute format('select %I::text, %I::text from %I where %I = $1'
                , lower(r_type.number_column), lower(r_type.status_column), lower(r_type.table_name), lower(r_type.pk_column))
      into x_doc_no, x_status
     using p_doc_id;
end;
$$;

create or replace function apx_demo_approval_pkg.set_doc_status(r_type apx_demo.apx_demo_doc_types, p_doc_id bigint, p_status text)
returns void language plpgsql
set search_path = apx_demo, pg_temp
as $$
begin
   perform apx_demo_approval_pkg.set_bypass(true);
   execute format('update %I set %I = $1 where %I = $2'
                , lower(r_type.table_name), lower(r_type.status_column), lower(r_type.pk_column))
     using p_status, p_doc_id;
   -- bila update gagal, seluruh transaksi batal dan setting transaksi ini ikut hilang
   perform apx_demo_approval_pkg.set_bypass(false);
end;
$$;

/** Nilai dokumen untuk aturan approval (amount_expr di apx_demo_doc_types). */
create or replace function apx_demo_approval_pkg.doc_amount(p_doc_type text, p_doc_id bigint)
returns numeric language plpgsql stable
set search_path = apx_demo, pg_temp
as $$
declare
   r_type   apx_demo_doc_types%rowtype := apx_demo_approval_pkg.get_type(p_doc_type);
   l_amount numeric;
begin
   if r_type.amount_expr is null then
      return 0;
   end if;
   -- amount_expr adalah konfigurasi (bukan input user)
   execute format('select %s from %I t where t.%I = $1', r_type.amount_expr, lower(r_type.table_name), lower(r_type.pk_column))
      into l_amount
     using p_doc_id;
   return coalesce(l_amount, 0);
end;
$$;

create or replace function apx_demo_approval_pkg.create_step(r_type apx_demo.apx_demo_doc_types, p_doc_id bigint
                                                           , p_level integer, p_role text, p_requested_by text)
returns void language plpgsql
set search_path = apx_demo, pg_temp
as $$
declare
   d record;
begin
   d := apx_demo_approval_pkg.get_doc(r_type, p_doc_id);
   insert into apx_demo_approvals (doc_type, doc_id, doc_no, approval_level, approver_role, amount, requested_by, requested_on, status)
   values (r_type.doc_type, p_doc_id, d.x_doc_no, p_level, p_role
         , apx_demo_approval_pkg.doc_amount(r_type.doc_type, p_doc_id), p_requested_by, localtimestamp(0), 'PENDING');
end;
$$;

/** Ajukan dokumen DRAFT/REJECTED untuk approval. */
create or replace procedure apx_demo_approval_pkg.submit(p_doc_type text, p_doc_id bigint)
language plpgsql
set search_path = apx_demo, pg_temp
as $$
declare
   r_type apx_demo_doc_types%rowtype := apx_demo_approval_pkg.get_type(p_doc_type);
   d      record;
begin
   d := apx_demo_approval_pkg.get_doc(r_type, p_doc_id);
   if d.x_status not in ('DRAFT', 'REJECTED') then
      raise exception 'Dokumen % berstatus % dan tidak dapat diajukan.', d.x_doc_no, d.x_status using hint = 'ORA-20101';
   end if;

   -- validasi khusus jenis dokumen (mis. budget check): procedure (p_doc_id bigint)
   if r_type.validate_proc is not null then
      if r_type.validate_proc !~* '^[a-z_][a-z0-9_]*(\.[a-z_][a-z0-9_]*)?$' then
         raise exception 'validate_proc tidak valid: %', r_type.validate_proc;
      end if;
      execute format('call %s($1)', lower(r_type.validate_proc)) using p_doc_id;
   end if;

   if r_type.approver1_role is null then
      perform apx_demo_approval_pkg.set_doc_status(r_type, p_doc_id, 'APPROVED');
   else
      perform apx_demo_approval_pkg.set_doc_status(r_type, p_doc_id, 'SUBMITTED');
      perform apx_demo_approval_pkg.create_step(r_type, p_doc_id, 1, r_type.approver1_role, apx_demo_sec_pkg.app_user());
   end if;
end;
$$;

/** Apakah user aktif boleh memproses approval ini: 'Y' atau 'N'. */
create or replace function apx_demo_approval_pkg.can_act_yn(p_approval_id bigint)
returns text language plpgsql stable
set search_path = apx_demo, pg_temp
as $$
declare
   r_appr apx_demo_approvals%rowtype;
begin
   select * into r_appr from apx_demo_approvals where approval_id = p_approval_id;
   if not found
      or r_appr.status <> 'PENDING'
      or upper(r_appr.requested_by) = apx_demo_sec_pkg.app_user()
   then
      return 'N';
   end if;
   return apx_demo_sec_pkg.has_role_yn(r_appr.approver_role);
end;
$$;

create or replace function apx_demo_approval_pkg.assert_can_act(r_appr apx_demo.apx_demo_approvals)
returns void language plpgsql stable
as $$
begin
   if r_appr.status <> 'PENDING' then
      raise exception 'Approval ini sudah diproses (%).', r_appr.status using hint = 'ORA-20105';
   end if;
   if upper(r_appr.requested_by) = apx_demo_sec_pkg.app_user() then
      raise exception 'Segregation of duties: pengaju tidak boleh menyetujui dokumennya sendiri.' using hint = 'ORA-20106';
   end if;
   if not apx_demo_sec_pkg.has_role(r_appr.approver_role) then
      raise exception 'Anda tidak memiliki role % untuk approval ini.', r_appr.approver_role using hint = 'ORA-20107';
   end if;
end;
$$;

create or replace function apx_demo_approval_pkg.lock_approval(p_approval_id bigint)
returns apx_demo.apx_demo_approvals language plpgsql
set search_path = apx_demo, pg_temp
as $$
declare
   r_appr apx_demo_approvals%rowtype;
begin
   select * into r_appr from apx_demo_approvals where approval_id = p_approval_id for update;
   if not found then
      raise exception 'Approval % tidak ditemukan.', p_approval_id;   -- Oracle: no_data_found
   end if;
   return r_appr;
end;
$$;

/** Setujui satu langkah approval (maker-checker, cek role). */
create or replace procedure apx_demo_approval_pkg.approve(p_approval_id bigint, p_note text default null)
language plpgsql
set search_path = apx_demo, pg_temp
as $$
declare
   r_appr apx_demo_approvals%rowtype := apx_demo_approval_pkg.lock_approval(p_approval_id);
   r_type apx_demo_doc_types%rowtype;
begin
   perform apx_demo_approval_pkg.assert_can_act(r_appr);

   update apx_demo_approvals
      set status   = 'APPROVED'
        , acted_by = apx_demo_sec_pkg.app_user()
        , acted_on = localtimestamp(0)
        , note     = p_note
    where approval_id = p_approval_id;

   r_type := apx_demo_approval_pkg.get_type(r_appr.doc_type);
   if r_appr.approval_level = 1
      and r_type.approver2_role is not null
      and coalesce(r_appr.amount, 0) > r_type.level2_limit
   then
      perform apx_demo_approval_pkg.create_step(r_type, r_appr.doc_id, 2, r_type.approver2_role, r_appr.requested_by);
   else
      perform apx_demo_approval_pkg.set_doc_status(r_type, r_appr.doc_id, 'APPROVED');
   end if;
end;
$$;

/** Tolak satu langkah approval (catatan wajib). */
create or replace procedure apx_demo_approval_pkg.reject(p_approval_id bigint, p_note text)
language plpgsql
set search_path = apx_demo, pg_temp
as $$
declare
   r_appr apx_demo_approvals%rowtype := apx_demo_approval_pkg.lock_approval(p_approval_id);
begin
   perform apx_demo_approval_pkg.assert_can_act(r_appr);
   if p_note is null then
      raise exception 'Alasan penolakan wajib diisi.' using hint = 'ORA-20108';
   end if;

   update apx_demo_approvals
      set status   = 'REJECTED'
        , acted_by = apx_demo_sec_pkg.app_user()
        , acted_on = localtimestamp(0)
        , note     = p_note
    where approval_id = p_approval_id;

   perform apx_demo_approval_pkg.set_doc_status(apx_demo_approval_pkg.get_type(r_appr.doc_type), r_appr.doc_id, 'REJECTED');
end;
$$;


-- Oracle: "create force view" boleh mendahului view yang dirujuknya; di PostgreSQL urutannya harus benar
create or replace view apx_demo_request_summary_v as
select r.request_id
     , r.request_no
     , d.dept_name
     , r.request_date
     , r.purpose
     , (select count(*) from apx_demo_request_lines l where l.request_id = r.request_id) as line_count
     , (select coalesce(sum(l.line_amount), 0) from apx_demo_request_lines l where l.request_id = r.request_id) as total_amount
     , r.status
  from apx_demo_requests r
  join apx_demo_departments d on d.department_id = r.department_id;


create or replace function apx_demo_requests_trg()
returns trigger language plpgsql
set search_path = apx_demo, pg_temp
as $$
begin
   if tg_op = 'INSERT' then
      if not apx_demo_approval_pkg.bypass() then
         new.status := 'DRAFT';
      end if;
      if new.request_no is null then
         new.request_no := apx_demo_doc_pkg.next_no('REQ');
      end if;
   elsif not apx_demo_approval_pkg.bypass() then
      if old.status = 'SUBMITTED' then
         raise exception 'Permintaan Barang % sedang menunggu approval dan tidak dapat diubah.', old.request_no using hint = 'ORA-20110';
      end if;
      if old.status in ('CANCELLED', 'CLOSED') then
         raise exception 'Permintaan Barang % sudah %.', old.request_no, old.status using hint = 'ORA-20111';
      end if;
      if new.status <> old.status
         and not (old.status in ('APPROVED', 'FULFILLED', 'CLOSED') and new.status in ('FULFILLED', 'CLOSED'))
      then
         raise exception 'Perubahan status % -> % tidak diizinkan. Gunakan Submit for Approval.', old.status, new.status using hint = 'ORA-20112';
      end if;
      -- kolom terkunci setelah approval (BR change management)
      if old.status not in ('DRAFT', 'REJECTED') then
         new.department_id := old.department_id;
         new.purpose       := old.purpose;
         new.need_date     := old.need_date;
      end if;
   end if;
   return jsonb_populate_record(new, apx_demo_audit(tg_op));
end;
$$;

create or replace function apx_demo_request_lines_trg()
returns trigger language plpgsql
set search_path = apx_demo, pg_temp
as $$
declare
   l_parent_status text;
begin
   select status into l_parent_status
     from apx_demo_requests
    where request_id = case when tg_op = 'DELETE' then old.request_id else new.request_id end;
   if not found then
      -- Oracle: ORA-04091 (mutating) saat delete cascade dari apx_demo_requests; di PostgreSQL induknya sudah terhapus
      return case when tg_op = 'DELETE' then old else new end;
   end if;
   if not apx_demo_approval_pkg.bypass() and l_parent_status not in ('DRAFT', 'REJECTED') then
      raise exception 'Baris Permintaan tidak dapat diubah karena Permintaan Barang berstatus %.', l_parent_status using hint = 'ORA-20121';
   end if;
   if tg_op = 'DELETE' then
      return old;
   end if;
   return jsonb_populate_record(new, apx_demo_audit(tg_op));
end;
$$;


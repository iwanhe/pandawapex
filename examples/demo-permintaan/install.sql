/** User aktif: APP_USER di sesi aplikasi, SESSION_USER di luar aplikasi (uppercase). */
create or replace function apx_demo_sec_pkg.app_user()
returns text language sql stable
as $$
   select upper(coalesce(nullif(current_setting('apx_demo.test_user', true), '')
                       , nullif(current_setting('rpx.app_user', true), '')
                       , session_user::text))
$$;

/** Mode bootstrap: TRUE selama belum ada user ber-role ADMIN. */
create or replace function apx_demo_sec_pkg.bootstrap_mode()
returns boolean language sql stable
set search_path = apx_demo, pg_temp
as $$ select not exists (select 1 from apx_demo_user_roles where role_code = 'ADMIN') $$;

/** Apakah user memiliki role (ADMIN selalu lolos; bootstrap -> semua lolos). */
create or replace function apx_demo_sec_pkg.has_role(p_role text, p_username text default null)
returns boolean language plpgsql stable
set search_path = apx_demo, pg_temp
as $$
begin
   if apx_demo_sec_pkg.bootstrap_mode() then
      return true;
   end if;
   return exists (select 1
                    from apx_demo_user_roles
                   where username = upper(coalesce(p_username, apx_demo_sec_pkg.app_user()))
                     and role_code in (upper(p_role), 'ADMIN'));
end;
$$;

/** Versi Y/N dari has_role, untuk dipakai di SQL. */
create or replace function apx_demo_sec_pkg.has_role_yn(p_role text, p_username text default null)
returns text language sql stable
as $$ select case when apx_demo_sec_pkg.has_role(p_role, p_username) then 'Y' else 'N' end $$;

/** Apakah user terdaftar (punya minimal satu role) atau mode bootstrap. */
create or replace function apx_demo_sec_pkg.has_any_role(p_username text default null)
returns boolean language plpgsql stable
set search_path = apx_demo, pg_temp
as $$
begin
   if apx_demo_sec_pkg.bootstrap_mode() then
      return true;
   end if;
   return exists (select 1 from apx_demo_user_roles
                   where username = upper(coalesce(p_username, apx_demo_sec_pkg.app_user())));
end;
$$;

/** HANYA untuk unit test di luar aplikasi: override user aktif (null untuk reset). Berlaku per koneksi. */
create or replace function apx_demo_sec_pkg.set_test_user(p_username text)
returns void language sql
as $$ select set_config('apx_demo.test_user', coalesce(upper(p_username), ''), false) $$;


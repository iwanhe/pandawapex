-- 7. Trigger: audit, penomoran, guard status
-- =============================================================================
create or replace function apx_demo_user_roles_trg()
returns trigger language plpgsql
set search_path = apx_demo, pg_temp
as $$
begin
   new.username  := upper(new.username);
   new.role_code := upper(new.role_code);
   return jsonb_populate_record(new, apx_demo_audit(tg_op));
end;
$$;

-- kolom audit sebagai jsonb: trigger menggabungkannya ke NEW dengan jsonb_populate_record
-- (PL/pgSQL tidak bisa mengisi field pada record polimorfik, jadi satu fungsi dipakai semua tabel)
create or replace function apx_demo_audit(p_op text)
returns jsonb language sql stable
as $$
   select jsonb_build_object('updated_by', apx_demo_sec_pkg.app_user(), 'updated_on', localtimestamp(0))

-- Demo Permintaan Barang: objek database untuk PostgreSQL (port dari install.sql Oracle, Tim PANDAWA 2026-11-01)
--
-- Jalankan sebagai pemilik skema SETELAH `rpx ws create` membuat skema-skema ini dan hak default untuk role ws_*:
--    apx_demo                tabel, view, trigger
--    apx_demo_sec_pkg        padanan package APX_DEMO_SEC_PKG
--    apx_demo_doc_pkg        padanan package APX_DEMO_DOC_PKG
--    apx_demo_approval_pkg   padanan package APX_DEMO_APPROVAL_PKG
--    apx_demo_request_pkg    padanan package APX_DEMO_REQUEST_PKG
-- Satu skema per package membuat pemanggilan tetap sama dengan Oracle: apx_demo_approval_pkg.submit(...).
-- Aman dijalankan ulang (create if not exists / create or replace / on conflict).
--
-- Pola terjemahan yang dipakai (lihat PORTING.md):
--    varchar2(n) -> varchar(n)      number -> numeric / bigint identity      date (dengan jam) -> timestamp(0)
--    sysdate -> localtimestamp      trunc(sysdate) -> current_date           nvl -> coalesce
--    raise_application_error -> raise exception      variabel package -> set_config / current_setting
--    merge ... + update ... returning -> insert ... on conflict do update ... returning
--    kolom virtual -> generated always as (...) stored      dbms_assert -> format('%I')
--------------------------------------------------------------------------------

